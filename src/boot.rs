//! The bootstrap (roadmap step 3, docs/plans/roadmap.md): the compiler compiling itself.
//!
//! - **Stage 0.** The interpreter runs `src/compiler.eel`, and that compiler compiles every
//!   top-level form of `src/compiler.eel`. The printed protos are **image 1**.
//! - **Stage 1.** A fresh engine loads image 1 *only*, so the compiler now runs as bytecode on
//!   the VM, and it compiles `src/compiler.eel` again: **image 2**.
//! - **Fixed point.** Image 1 and image 2 must be identical, character for character.
//! - **Stage 2.** The same, but the source is read by the EELisp reader (`src/reader.eel`) too,
//!   not by the Rust parser: text to bytecode in EELisp alone. Image 3 must be identical as well.
//!
//! The image is committed as `boot/compiler.image`, so an engine can start a compiler without
//! interpreting its source. `cargo run --example bootstrap` regenerates it; the tree-walking
//! interpreter remains the way to rebuild it from source, so nothing depends on a binary nobody
//! can reproduce.
//!
//! An image is plain EELisp text: one `(proto …)` form per top-level form of the source, in
//! order. Loading it runs each one at the top level, which defines the compiler's functions.

use crate::interpreter::Interpreter;
use crate::parser;
use crate::printer::print_value;
use crate::value::{LispError, Value};
use crate::vm;

/// The compiler's source.
pub const COMPILER: &str = include_str!("compiler.eel");

/// The reader's source: text in, forms out, written in EELisp (the Rust one is `parser::parse`).
pub const READER: &str = include_str!("reader.eel");

/// Everything the image is made from, in order: the compiler, then the reader.
pub fn source() -> String {
    format!("{COMPILER}\n{READER}")
}

/// The compiler, compiled by itself: what compiled mode loads (`Interpreter::set_compiled`).
/// `tests/bootstrap.rs` fails if it's out of date with `COMPILER`.
pub const IMAGE: &str = include_str!("../boot/compiler.image");

const HEADER: &str = ";; The EELisp compiler and reader, compiled by the compiler: one (proto …) per top-level form of
;; src/compiler.eel and then src/reader.eel, in order. Generated by `cargo run --example bootstrap`;
;; don't edit by hand.
";

/// Compile every top-level form of `src` with the compiler loaded in `it`, as image text.
pub fn compile_image(it: &Interpreter, src: &str) -> Result<String, LispError> {
    image_of(it, parser::parse(src)?)
}

/// Compile each form with the compiler loaded in `it`, as image text.
fn image_of(it: &Interpreter, forms: Vec<Value>) -> Result<String, LispError> {
    let mut out = String::from(HEADER);
    for form in forms {
        let proto = it.call("compile", &[form]).ok_or_else(|| {
            LispError::Runtime("there is no compiler loaded (no `compile` function)".into())
        })??;
        out.push_str(&print_value(&proto, true));
        out.push('\n');
    }
    Ok(out)
}

/// Run an image's protos at the top level of `it`, in order.
pub fn load_image(it: &Interpreter, image: &str) -> Result<(), LispError> {
    for form in parser::parse(image)? {
        vm::run_in(vm::assemble(&form)?, it.global.clone())?;
    }
    Ok(())
}

/// Stage 0: the interpreted compiler compiles itself.
pub fn stage0() -> Result<String, LispError> {
    stage0_of(&source())
}

/// Stage 0 for any source: the interpreter runs it, then it compiles itself.
pub fn stage0_of(src: &str) -> Result<String, LispError> {
    let it = interpreting()?;
    it.eval_all(src)?;
    compile_image(&it, src)
}

/// Stage 1: the compiler loaded from `image` — bytecode only — compiles itself.
pub fn stage1(image: &str) -> Result<String, LispError> {
    compile_image(&with_image(image)?, &source())
}

/// Stage 2: no Rust between the text and the bytecode. The engine loaded from `image` reads the
/// source with the EELisp reader (`read-all`) and compiles it with the EELisp compiler. Rust only
/// runs the VM and the builtins.
pub fn stage2(image: &str) -> Result<String, LispError> {
    next_image(image, &source())
}

/// One generation: the reader and compiler in `image` read and compile `src`. With `src` the
/// source `image` was made from, that's `image` again; with a newer source, it's the next image.
pub fn next_image(image: &str, src: &str) -> Result<String, LispError> {
    let it = with_image(image)?;
    let forms = it
        .call("read-all", &[Value::Str(src.into())])
        .ok_or_else(|| {
            LispError::Runtime("the image has no reader (no `read-all` function)".into())
        })??;
    match forms {
        Value::List(l) => image_of(&it, l.to_vec()),
        other => Err(LispError::Runtime(format!(
            "read-all returned {}",
            print_value(&other, true)
        ))),
    }
}

/// The three generations of a rebuild (see `rebuild`).
pub struct Rebuild {
    /// The new source, read and compiled by the old image.
    pub first: String,
    /// The new source, compiled by itself (by `first`).
    pub second: String,
    /// Once more, by `second`. Must equal `second`.
    pub third: String,
}

/// Build the image for `src` from an older image, the way self-hosted compilers build their next
/// version: the old compiler compiles the new source (`first`), that compiler compiles the source
/// again (`second`), and once more (`third`). `second` and `third` are the new compiler compiled
/// by itself, so they must be identical; `first` may differ from them, when the new source changes
/// what the compiler emits. The interpreter isn't involved: `stage0_of` is the cross-check.
pub fn rebuild(old: &str, src: &str) -> Result<Rebuild, LispError> {
    let first = next_image(old, src)?;
    let second = next_image(&first, src)?;
    let third = next_image(&second, src)?;
    if second != third {
        let line = second.lines().zip(third.lines()).position(|(a, b)| a != b);
        return Err(LispError::Runtime(format!(
            "the rebuilt compiler is not a fixed point (generations 2 and 3 first differ at line {line:?})"
        )));
    }
    Ok(Rebuild {
        first,
        second,
        third,
    })
}

/// A fresh engine with the compiler loaded from `image`; its source is never interpreted.
pub fn with_image(image: &str) -> Result<Interpreter, LispError> {
    let it = interpreting()?;
    load_image(&it, image)?;
    Ok(it)
}

/// A fresh engine that interprets, whatever `EELISP_COMPILED` says: stage 0 has to be the
/// interpreted compiler.
fn interpreting() -> Result<Interpreter, LispError> {
    let it = Interpreter::new();
    it.set_compiled(false)?;
    Ok(it)
}
